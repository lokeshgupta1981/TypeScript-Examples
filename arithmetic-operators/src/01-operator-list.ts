export function operatorList(): void {
  const x = 10;
  const y = 4;

  console.log("x + y =", x + y);                // 14
  console.log("x - y =", x - y);                // 6
  console.log("x * y =", x * y);                // 40
  console.log("x / y =", x / y);                // 2.5
  console.log("x % y =", x % y);                // 2
  console.log("x ** 2 =", x ** 2);              // 100
  console.log("-x =", -x);                      // -10
  console.log('+"7" =', +"7");                  // 7
}
